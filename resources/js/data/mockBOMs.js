import { PRODUCT_SEED } from './mockProducts';

const productBySku = PRODUCT_SEED.reduce((map, product) => {
    map[product.sku] = product;
    return map;
}, {});

function ref(sku) {
    const product = productBySku[sku];
    return product
        ? { id: product.id, name: product.name, sku: product.sku, category: product.category }
        : { id: sku, name: sku, sku, category: '' };
}

function makeLine({ id, parentSku, componentName, componentCode, quantity, unit, level, status, revision, supplier, lastUpdated, notes, children = [] }) {
    const parentProduct = ref(parentSku);
    return {
        id,
        parentProduct,
        componentName,
        componentCode,
        quantity,
        unit,
        level,
        status,
        revision,
        supplier,
        lastUpdated,
        notes,
        children,
    };
}

